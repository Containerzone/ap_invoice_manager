CREATE TABLE `financial_for_hire_po_events` (
	`id` int AUTO_INCREMENT NOT NULL,
	`containerControlId` varchar(128) NOT NULL,
	`containerControlNumber` varchar(128) NOT NULL,
	`eventKind` enum('initial','recurring') NOT NULL,
	`billingPeriodStart` varchar(10) NOT NULL,
	`billingPeriodEnd` varchar(10) NOT NULL,
	`proposedPoNumber` varchar(128) NOT NULL,
	`containerNumber` varchar(128) NOT NULL,
	`containerType` varchar(80) NOT NULL,
	`supplierVtigerId` varchar(128),
	`supplierName` varchar(255),
	`sourceRefreshedAt` timestamp,
	`sourceSnapshotHash` varchar(64) NOT NULL,
	`rulesSnapshotHash` varchar(64) NOT NULL,
	`xeroPreflightHash` varchar(64),
	`proposal` json,
	`xeroPreflight` json,
	`xeroPurchaseOrderId` varchar(128),
	`status` enum('previewed','held','reserved','drafts_created','reconciliation_required','dehired') NOT NULL DEFAULT 'previewed',
	`holdReason` text,
	`executionId` int,
	`alertStatus` varchar(64),
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `financial_for_hire_po_events_id` PRIMARY KEY(`id`),
	CONSTRAINT `financial_for_hire_po_control_period_unique` UNIQUE(`containerControlId`,`eventKind`,`billingPeriodStart`),
	CONSTRAINT `financial_for_hire_po_proposed_number_unique` UNIQUE(`proposedPoNumber`)
);
