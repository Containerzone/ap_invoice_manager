CREATE TABLE `financial_final_weight_reconciliation_events` (
	`id` int AUTO_INCREMENT NOT NULL,
	`originalEventId` int NOT NULL,
	`recoveryKey` varchar(64) NOT NULL,
	`direction` enum('overweight','underweight') NOT NULL,
	`dealId` varchar(128) NOT NULL,
	`dealNumber` varchar(128) NOT NULL,
	`invoiceNumber` varchar(128) NOT NULL,
	`xeroInvoiceId` varchar(128) NOT NULL,
	`originalEventHash` varchar(64) NOT NULL,
	`sourceSnapshotHash` varchar(64) NOT NULL,
	`xeroPreflightHash` varchar(64) NOT NULL,
	`sourceSnapshot` json NOT NULL,
	`xeroPreflight` json NOT NULL,
	`originalDraft` json NOT NULL,
	`expectedDraft` json NOT NULL,
	`originalDraftHash` varchar(64) NOT NULL,
	`expectedDraftHash` varchar(64) NOT NULL,
	`releaseKey` varchar(128),
	`authorisedPayload` json,
	`processingToken` varchar(128),
	`status` enum('previewed','reserved','submitted','draft_updated','reconciliation_required') NOT NULL DEFAULT 'previewed',
	`holdReason` text,
	`executionId` int,
	`submittedAt` timestamp,
	`readbackEvidence` json,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `financial_final_weight_reconciliation_events_id` PRIMARY KEY(`id`),
	CONSTRAINT `financial_final_weight_reconcile_original_unique` UNIQUE(`originalEventId`),
	CONSTRAINT `financial_final_weight_reconcile_key_unique` UNIQUE(`recoveryKey`),
	CONSTRAINT `financial_final_weight_reconcile_invoice_unique` UNIQUE(`xeroInvoiceId`)
);
