	`id` int AUTO_INCREMENT NOT NULL,
	`eventKey` varchar(160) NOT NULL,
	`claimKey` varchar(128),
	`executionGroup` varchar(128),
	`dealId` varchar(128) NOT NULL,
	`dealNumber` varchar(128),
	`status` enum('previewed','held','reserved','main_submitted','main_receipt','po_submitted','po_receipt','drafts_created','reconciliation_required') NOT NULL,
	`sourceSnapshotHash` varchar(64),
	`sourceMappingsHash` varchar(64),
	`addedServicesMappingHash` varchar(64),
	`xeroPreflightHash` varchar(64),
	`sourceSnapshot` json,
	`xeroPreflight` json,
	`proposal` json,
	`authorisedPayload` json,
	`releaseKey` varchar(128),
	`approvedBy` int,
	`receipt` json,
	`holdReason` text,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
