CREATE TABLE `financial_deposit_invoice_events` (
	`id` int AUTO_INCREMENT NOT NULL,
	`evidenceKey` varchar(64) NOT NULL,
	`dealId` varchar(128) NOT NULL,
	`dealNumber` varchar(128) NOT NULL,
	`proposedInvoiceNumber` varchar(128) NOT NULL,
	`customerVtigerId` varchar(128),
	`customerName` varchar(255),
	`sourceRefreshedAt` timestamp,
	`sourceSnapshotHash` varchar(64) NOT NULL,
	`rulesSnapshotHash` varchar(64) NOT NULL,
	`xeroPreflightHash` varchar(64),
	`sourceSnapshot` json NOT NULL,
	`proposal` json,
	`xeroPreflight` json,
	`postconditionHold` text NOT NULL,
	`claimedDealId` varchar(128),
	`claimedInvoiceNumber` varchar(128),
	`releaseKey` varchar(128),
	`authorisedPayload` json,
	`processingToken` varchar(128),
	`status` enum('previewed','held','reserved','drafts_created','reconciliation_required') NOT NULL DEFAULT 'held',
	`holdReason` text,
	`executionId` int,
	`xeroInvoiceId` varchar(128),
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `financial_deposit_invoice_events_id` PRIMARY KEY(`id`),
	CONSTRAINT `financial_deposit_invoice_evidence_unique` UNIQUE(`evidenceKey`),
	CONSTRAINT `financial_deposit_invoice_claimed_deal_unique` UNIQUE(`claimedDealId`),
	CONSTRAINT `financial_deposit_invoice_claimed_number_unique` UNIQUE(`claimedInvoiceNumber`)
);
