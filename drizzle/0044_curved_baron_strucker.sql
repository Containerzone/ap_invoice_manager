CREATE TABLE `financial_extra_hire_invoice_events` (
	`id` int AUTO_INCREMENT NOT NULL,
	`evidenceKey` varchar(64) NOT NULL,
	`dealId` varchar(128) NOT NULL,
	`dealNumber` varchar(128) NOT NULL,
	`sourceHireEndDate` varchar(10),
	`ordinal` int,
	`proposedInvoiceNumber` varchar(128),
	`customerName` varchar(255),
	`sourceRefreshedAt` timestamp,
	`preflightAt` timestamp NOT NULL,
	`sourceSnapshotHash` varchar(64) NOT NULL,
	`rulesSnapshotHash` varchar(64) NOT NULL,
	`xeroPreflightHash` varchar(64),
	`sourceSnapshot` json NOT NULL,
	`proposal` json,
	`xeroPreflight` json,
	`claimedPeriodKey` varchar(160),
	`claimedOrdinalKey` varchar(160),
	`claimedInvoiceNumber` varchar(128),
	`releaseKey` varchar(128),
	`authorisedPayload` json,
	`processingToken` varchar(128),
	`status` enum('previewed','held','reserved','submitted','drafts_created','reconciliation_required') NOT NULL DEFAULT 'held',
	`holdReason` text,
	`postconditionHold` text NOT NULL,
	`executionId` int,
	`xeroInvoiceId` varchar(128),
	`submittedAt` timestamp,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `financial_extra_hire_invoice_events_id` PRIMARY KEY(`id`),
	CONSTRAINT `financial_extra_hire_evidence_unique` UNIQUE(`evidenceKey`),
	CONSTRAINT `financial_extra_hire_period_claim_unique` UNIQUE(`claimedPeriodKey`),
	CONSTRAINT `financial_extra_hire_ordinal_claim_unique` UNIQUE(`claimedOrdinalKey`),
	CONSTRAINT `financial_extra_hire_invoice_claim_unique` UNIQUE(`claimedInvoiceNumber`)
);
